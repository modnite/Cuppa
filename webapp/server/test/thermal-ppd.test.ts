import assert from "node:assert/strict";
import { test } from "node:test";
import { defaultThermalConfig } from "../src/thermal/config.js";
import { buildThermalPpd } from "../src/thermal/ppd.js";

/**
 * The generated PPD is parsed by CUPS, so every required key, the mm -> point
 * rounding and the filter routing lines are pinned down.
 */

const base = defaultThermalConfig();

test("buildThermalPpd emits the required PPD structure", () => {
  const ppd = buildThermalPpd(base, "My Label");
  for (const key of [
    '*PPD-Adobe: "4.3"',
    '*FormatVersion: "4.3"',
    '*FileVersion: "1.0"',
    "*LanguageVersion: English",
    "*LanguageEncoding: ISOLatin1",
    '*PCFileName: "CUPPA.PPD"',
    '*Manufacturer: "Cuppa"',
    '*Product: "(Thermal)"',
    "*ColorDevice: False",
    "*DefaultColorSpace: Gray",
    "*FileSystem: False",
    '*Throughput: "1"',
    "*LandscapeOrientation: Plus90",
    "*TTRasterizer: Type42",
  ]) {
    assert.ok(ppd.includes(key), `missing ${key}`);
  }
  assert.ok(ppd.endsWith("*% End of PPD\n"));
});

test("buildThermalPpd names the model and resolution after the dialect", () => {
  const ppd = buildThermalPpd(defaultThermalConfig({ dialect: "zpl", dpi: 300 }), "Label");
  assert.ok(ppd.includes('*ModelName: "Cuppa Thermal (ZPL)"'));
  assert.ok(ppd.includes('*NickName: "Cuppa Thermal ZPL"'));
  assert.ok(ppd.includes("*DefaultResolution: 300dpi"));
  assert.ok(
    ppd.includes('*Resolution 300dpi/300 DPI: "<</HWResolution[300 300]>>setpagedevice"')
  );
});

test("buildThermalPpd rounds mm to points and derives the page name", () => {
  const ppd = buildThermalPpd(
    defaultThermalConfig({ labelWidthMm: 101.6, labelHeightMm: 152.4 }),
    "4x6"
  );
  assert.ok(ppd.includes("*DefaultPageSize: w288h432"));
  assert.ok(ppd.includes('*PageSize w288h432/4x6: "<</PageSize[288 432]/ImagingBBox null>>setpagedevice"'));
  assert.ok(ppd.includes('*PageRegion w288h432/4x6: "<</PageSize[288 432]/ImagingBBox null>>setpagedevice"'));
  assert.ok(ppd.includes('*ImageableArea w288h432/4x6: "0 0 288 432"'));
  assert.ok(ppd.includes('*PaperDimension w288h432/4x6: "288 432"'));

  const small = buildThermalPpd(defaultThermalConfig({ labelWidthMm: 2, labelHeightMm: 5 }), "small");
  // 2 mm -> 5.67 -> 6 pt; 5 mm -> 14.17 -> 14 pt.
  assert.ok(small.includes("*DefaultPageSize: w6h14"));
});

test("buildThermalPpd routes PDF and PostScript through the cuppa-thermal filter", () => {
  const ppd = buildThermalPpd(base, "Label");
  const filters = ppd.split(/\r?\n/).filter((line) => line.startsWith("*cupsFilter2:"));
  assert.deepEqual(filters, [
    '*cupsFilter2: "application/pdf application/vnd.cuppa.thermal 0 cuppa-thermal"',
    '*cupsFilter2: "application/postscript application/vnd.cuppa.thermal 0 cuppa-thermal"',
  ]);
});

test("buildThermalPpd puts the label into the generated-by comment", () => {
  assert.ok(buildThermalPpd(base, "Office Laser (Cuppa)").includes("*% Generated by Cuppa for Office Laser (Cuppa)"));
});
